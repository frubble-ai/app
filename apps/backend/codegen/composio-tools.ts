import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { Composio } from "@composio/core";
import { compile } from "json-schema-to-typescript";
import type {
	TJsonSchema,
	TSchemaPatch,
} from "../src/composio/lib/output-schema.ts";
import { typeTeams } from "../src/composio/linear/lib/output-patch.ts";

// The `data` type of each Composio tool the backend calls, generated from Composio's own output
// schema with the same patch the runtime check applies; one file per tool. Needs COMPOSIO_API_KEY.
// Runs under Node (the image's build stage has no Bun), so its imports are relative.

const TOOLS: Record<string, TSchemaPatch | undefined> = {
	LINEAR_LIST_LINEAR_TEAMS: typeTeams,
	SLACK_LIST_ALL_CHANNELS: undefined,
};

const OUT = path.join(import.meta.dirname, "../src/__generated__/composio");

const apiKey = process.env.COMPOSIO_API_KEY;
if (!apiKey)
	throw new Error("COMPOSIO_API_KEY is needed to generate the tool types");
const composio = new Composio({
	apiKey,
	allowTracking: false,
	disableVersionCheck: true,
});

/** Titles name a type per field; without them the fields stay inline and the $defs keep names. */
function withoutTitles(value: unknown): unknown {
	if (Array.isArray(value)) return value.map(withoutTitles);
	if (!value || typeof value !== "object") return value;
	return Object.fromEntries(
		Object.entries(value)
			.filter(([key]) => key !== "title")
			.map(([key, entry]) => [key, withoutTitles(entry)]),
	);
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
const index: string[] = [];
for (const [slug, patch] of Object.entries(TOOLS)) {
	const tool = await composio.tools.getRawComposioToolBySlug(slug);
	const output = tool.outputParameters as TJsonSchema & {
		properties?: { data?: TJsonSchema };
		$defs?: TJsonSchema;
	};
	const data = { ...output.properties?.data, $defs: output.$defs };
	const file = slug.toLowerCase().replaceAll("_", "-");
	const types = await compile(
		withoutTitles(patch ? patch(data) : data) as never,
		"Data",
		{
			bannerComment: `// Generated by codegen/composio-tools.ts from Composio's ${slug} schema. Do not edit.`,
			additionalProperties: false,
			unreachableDefinitions: false,
			format: false,
		},
	);
	writeFileSync(path.join(OUT, `${file}.ts`), types);
	index.push(`\t${slug}: import("./${file}").Data;`);
}
writeFileSync(
	path.join(OUT, "index.ts"),
	`// Generated by codegen/composio-tools.ts. Do not edit.\n\n/** Each Composio tool's \`data\`, by slug. */\nexport type TComposioToolData = {\n${index.join("\n")}\n};\n`,
);
